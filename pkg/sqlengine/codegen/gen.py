def gen_dtypes() -> None:
    lines = ["// DType mirrors sqlglot.expressions.DataType.Type.\ntype DType uint16\n\nconst (\n"]
    lines.append("\tDT_NONE DType = 0\n")
    for i, d in enumerate(DTYPES):
        lines.append("\t%s DType = %d\n" % (dt(d), i + 1))
    lines.append(")\n\nconst numDTypes = %d\n\n" % (len(DTYPES) + 1))
    lines.append("var dtypeNames = [numDTypes]string{\n")
    for d in DTYPES:
        lines.append("\t%s: %s,\n" % (dt(d), gostr(d.name)))
    lines.append("}\n\nvar dtypeValues = [numDTypes]string{\n")
    for d in DTYPES:
        lines.append("\t%s: %s,\n" % (dt(d), gostr(d.value)))
    lines.append("}\n\n")
    for attr in sorted(vars(exp.DataType)):
        v = getattr(exp.DataType, attr)
        if attr.isupper() and isinstance(v, (set, frozenset)):
            lines.append(
                "var DataType_%s = newDTypeSet(%s)\n" % (attr, ", ".join(dt(x) for x in sorted(v, key=lambda x: x.name)))
            )
    write("zz_dtypes.go", "".join(lines))


