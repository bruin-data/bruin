// Package dac installs the pinned dac release that backs `bruin dac` and runs it
// as a separate process. dac is never compiled into Bruin.
package dac

import (
	"archive/tar"
	"archive/zip"
	"compress/gzip"
	"context"
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"sync"
	"time"

	"github.com/pkg/errors"
)

const (
	releaseDownloadURL = "https://github.com/bruin-data/dac/releases/download"
	maxArchiveSize     = 512 * 1024 * 1024
	maxBinarySize      = 512 * 1024 * 1024
	windowsOS          = "windows"
)

// installMu serializes installs within one Bruin process. Separate processes are
// safe because each one downloads into its own temporary directory and moves the
// finished binary into place with a single rename.
var installMu sync.Mutex

// release.json is regenerated by `make dac-pins DAC_VERSION=x.y.z`.
//
//go:embed release.json
var releaseJSON []byte

// Release is a dac version together with the SHA-256 of each release archive.
type Release struct {
	Version  string            `json:"version"`
	Archives map[string]string `json:"archives"`
}

// PinnedRelease returns the dac release this Bruin build runs.
func PinnedRelease() (Release, error) {
	var release Release
	if err := json.Unmarshal(releaseJSON, &release); err != nil {
		return Release{}, errors.Wrap(err, "invalid embedded dac release pins")
	}
	if release.Version == "" || len(release.Archives) == 0 {
		return Release{}, errors.New("embedded dac release pins are empty")
	}
	return release, nil
}

// Installer installs one dac release into <home>/dac/<version>/.
type Installer struct {
	Release    Release
	HomeDir    string
	GOOS       string
	GOARCH     string
	BaseURL    string
	HTTPClient *http.Client
	// Output receives progress messages. Use stderr: stdout belongs to dac.
	Output io.Writer
}

// NewInstaller returns an installer for the pinned release on this OS/arch.
func NewInstaller(homeDir string, output io.Writer) (*Installer, error) {
	release, err := PinnedRelease()
	if err != nil {
		return nil, err
	}
	return &Installer{
		Release:    release,
		HomeDir:    homeDir,
		GOOS:       runtime.GOOS,
		GOARCH:     runtime.GOARCH,
		BaseURL:    releaseDownloadURL,
		HTTPClient: &http.Client{Timeout: 5 * time.Minute},
		Output:     output,
	}, nil
}

// BinaryPath is where the managed dac binary lives once installed.
func (i *Installer) BinaryPath() string {
	return filepath.Join(i.versionDir(), binaryName(i.GOOS))
}

func (i *Installer) versionDir() string {
	return filepath.Join(i.HomeDir, "dac", i.Release.Version)
}

// EnsureInstalled returns the managed dac binary, downloading and verifying the
// pinned release first if it is not installed yet. An installed binary is reused
// without touching the network.
func (i *Installer) EnsureInstalled(ctx context.Context) (string, error) {
	installMu.Lock()
	defer installMu.Unlock()

	binaryPath := i.BinaryPath()
	if isRegularFile(binaryPath) {
		return binaryPath, nil
	}

	archiveName, err := ArchiveName(i.GOOS, i.GOARCH)
	if err != nil {
		return "", fmt.Errorf("%w\n\nBuild dac from source (https://github.com/bruin-data/dac) and run it through Bruin with BRUIN_DAC_BINARY=/path/to/dac", err)
	}
	expected := i.Release.Archives[archiveName]
	if len(expected) != sha256.Size*2 {
		return "", i.installError(archiveName, "", fmt.Errorf("this Bruin build has no pinned SHA-256 for %s", archiveName))
	}

	if err := i.install(ctx, archiveName, expected); err != nil {
		if ctx.Err() != nil {
			return "", errors.Wrapf(ctx.Err(), "dac v%s install stopped", i.Release.Version)
		}
		return "", i.installError(archiveName, expected, err)
	}
	return binaryPath, nil
}

func (i *Installer) install(ctx context.Context, archiveName, expected string) error {
	installRoot := filepath.Join(i.HomeDir, "dac")
	if err := os.MkdirAll(installRoot, 0o755); err != nil {
		return errors.Wrap(err, "failed to create the dac installation directory")
	}
	tempDir, err := os.MkdirTemp(installRoot, ".install-"+i.Release.Version+"-")
	if err != nil {
		return errors.Wrap(err, "failed to create a temporary dac installation directory")
	}
	defer os.RemoveAll(tempDir)

	_, _ = fmt.Fprintf(i.Output, "Installing dac v%s into %s (one-time download)...\n", i.Release.Version, i.versionDir())

	archivePath := filepath.Join(tempDir, archiveName)
	if err := i.download(ctx, i.downloadURL(archiveName), archivePath, expected); err != nil {
		return err
	}

	name := binaryName(i.GOOS)
	tempBinaryPath := filepath.Join(tempDir, name)
	if strings.HasSuffix(archiveName, ".zip") {
		err = extractFromZip(archivePath, name, tempBinaryPath)
	} else {
		err = extractFromTarGz(archivePath, name, tempBinaryPath)
	}
	if err != nil {
		return err
	}

	versionDir := i.versionDir()
	if err := os.MkdirAll(versionDir, 0o755); err != nil {
		return errors.Wrap(err, "failed to create the versioned dac installation directory")
	}
	if err := os.Rename(tempBinaryPath, i.BinaryPath()); err != nil {
		// Another Bruin process may have finished the same install first.
		if isRegularFile(i.BinaryPath()) {
			return nil
		}
		// Only removes the directory if it is still empty.
		_ = os.Remove(versionDir)
		return errors.Wrap(err, "failed to move dac into place")
	}
	return nil
}

func (i *Installer) download(ctx context.Context, downloadURL, destination, expected string) error {
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, downloadURL, nil)
	if err != nil {
		return errors.Wrap(err, "failed to create the dac download request")
	}
	response, err := i.HTTPClient.Do(request)
	if err != nil {
		// The error already names the URL.
		return errors.Wrap(err, "download failed")
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return fmt.Errorf("failed to download %s: server returned %s", downloadURL, response.Status)
	}

	file, err := os.Create(destination)
	if err != nil {
		return errors.Wrap(err, "failed to create the dac archive file")
	}
	hash := sha256.New()
	written, copyErr := io.Copy(io.MultiWriter(file, hash), io.LimitReader(response.Body, maxArchiveSize+1))
	closeErr := file.Close()
	if copyErr != nil {
		return errors.Wrapf(copyErr, "failed to download %s", downloadURL)
	}
	if closeErr != nil {
		return errors.Wrap(closeErr, "failed to write the dac archive")
	}
	if written > maxArchiveSize {
		return fmt.Errorf("%s is larger than the %d-byte limit", downloadURL, maxArchiveSize)
	}
	if actual := hex.EncodeToString(hash.Sum(nil)); actual != expected {
		return fmt.Errorf("SHA-256 mismatch for %s: expected %s, got %s", filepath.Base(destination), expected, actual)
	}
	return nil
}

func (i *Installer) downloadURL(archiveName string) string {
	return strings.TrimRight(i.BaseURL, "/") + "/v" + i.Release.Version + "/" + archiveName
}

// installError explains what failed and how to put the pinned dac in place by hand.
func (i *Installer) installError(archiveName, expected string, cause error) error {
	var hint strings.Builder
	fmt.Fprintf(&hint, "To install dac v%s manually, download %s", i.Release.Version, releaseDownloadURL+"/v"+i.Release.Version+"/"+archiveName)
	if expected != "" {
		fmt.Fprintf(&hint, ", check that its SHA-256 is %s,", expected)
	}
	fmt.Fprintf(&hint, " and extract %s from it to %s", binaryName(i.GOOS), i.BinaryPath())
	if i.GOOS != windowsOS {
		hint.WriteString(" (chmod +x it)")
	}
	hint.WriteString(".\nTo use a dac binary you installed or built yourself, set BRUIN_DAC_BINARY=/path/to/dac.")
	return fmt.Errorf("failed to install dac v%s: %w\n\n%s", i.Release.Version, cause, hint.String())
}

// ArchiveName returns the dac release archive for an OS/arch pair.
func ArchiveName(goos, goarch string) (string, error) {
	osName := map[string]string{"linux": "Linux", "darwin": "Darwin", windowsOS: "Windows"}[goos]
	archName := map[string]string{"amd64": "x86_64", "arm64": "arm64"}[goarch]
	if osName == "" || archName == "" || (goos == windowsOS && goarch != "amd64") {
		return "", fmt.Errorf("dac has no release for %s/%s", goos, goarch)
	}
	if goos == windowsOS {
		return "dac_" + osName + "_" + archName + ".zip", nil
	}
	return "dac_" + osName + "_" + archName + ".tar.gz", nil
}

func binaryName(goos string) string {
	if goos == windowsOS {
		return "dac.exe"
	}
	return "dac"
}

func isRegularFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

func extractFromTarGz(archivePath, name, destination string) error {
	file, err := os.Open(archivePath)
	if err != nil {
		return errors.Wrap(err, "failed to open the dac archive")
	}
	defer file.Close()
	gz, err := gzip.NewReader(file)
	if err != nil {
		return errors.Wrap(err, "failed to read the dac archive")
	}
	defer gz.Close()

	reader := tar.NewReader(gz)
	for {
		header, err := reader.Next()
		if errors.Is(err, io.EOF) {
			return fmt.Errorf("the dac archive does not contain %s", name)
		}
		if err != nil {
			return errors.Wrap(err, "failed to read the dac archive")
		}
		if header.Typeflag == tar.TypeReg && filepath.Base(filepath.ToSlash(header.Name)) == name {
			return writeBinary(reader, destination)
		}
	}
}

func extractFromZip(archivePath, name, destination string) error {
	archive, err := zip.OpenReader(archivePath)
	if err != nil {
		return errors.Wrap(err, "failed to open the dac archive")
	}
	defer archive.Close()

	for _, file := range archive.File {
		if !file.Mode().IsRegular() || filepath.Base(filepath.ToSlash(file.Name)) != name {
			continue
		}
		reader, err := file.Open()
		if err != nil {
			return errors.Wrap(err, "failed to read the dac archive")
		}
		defer reader.Close()
		return writeBinary(reader, destination)
	}
	return fmt.Errorf("the dac archive does not contain %s", name)
}

func writeBinary(source io.Reader, destination string) error {
	file, err := os.OpenFile(destination, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o755)
	if err != nil {
		return errors.Wrap(err, "failed to create the dac binary")
	}
	written, copyErr := io.Copy(file, io.LimitReader(source, maxBinarySize+1))
	closeErr := file.Close()
	if copyErr != nil {
		return errors.Wrap(copyErr, "failed to extract the dac binary")
	}
	if closeErr != nil {
		return errors.Wrap(closeErr, "failed to write the dac binary")
	}
	if written > maxBinarySize {
		return fmt.Errorf("the dac binary is larger than the %d-byte limit", maxBinarySize)
	}
	return nil
}
